import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {check} from './src/compiler.ts';
import {resolve} from './src/runtime.ts';
import {dateTimeTz,epochMillis,parseDateTimeTz} from './src/time-values.ts';
import {primaryCodecs} from './src/primary-codecs.ts';
const {dariHost}=await import(new URL('../../dsh-oks/packages/dsh-oks/src/dari-host.ts',import.meta.url).href);
const db=new DatabaseSync(':memory:');
const run=(source:string)=>{const name=[...source.matchAll(/data (\w+)=/g)].at(-1)![1];return resolve(check(source+'answer tree! { Answer ['+(name==='rows'?'UseTable(ref = rows)':'Value(value = '+name+')')+']};',undefined,{host:dariHost}),db).values;};
assert.equal(run('data t=EpochMillis(0);data later=t+1000;data delta=later-t;').delta,1000);
assert.equal(run('data t=to_datetime_utc(EpochMillis(0));').t,'1970-01-01T00:00:00.000Z');
assert.equal(run('data t=to_datetime_tz(EpochMillis(0),"Asia/Shanghai");').t,'1970-01-01T08:00:00.000+08:00[Asia/Shanghai]');
assert.equal(run('data t=time_bucket(DateTimeUtc("2026-03-08T20:00:00Z"),{unit:TimeUnit::Day,time_zone:"America/New_York"});').t,'2026-03-08T05:00:00.000Z');
assert.throws(()=>primaryCodecs.EpochMillis.parse('0'),/requires Int/);
assert.throws(()=>primaryCodecs.DateTimeUtc.parse(0),/requires ISO String/);
assert.throws(()=>epochMillis('2026-02-30T00:00:00Z'),/calendar/);
assert.throws(()=>epochMillis('2026-01-01T24:00:00Z'),/clock/);
assert.throws(()=>parseDateTimeTz('2026-07-01T00:00:00.000-05:00[America/New_York]'),/offset/);
const instant=epochMillis('2026-11-01T06:30:00Z');
assert.equal(epochMillis(dateTimeTz(instant,'America/New_York')),instant);
const output=resolve(check('data p=Percent(12.0);data r=Ratio(0.12);answer tree! { Answer [Value(value = p),Value(value = r)]};'),db);
assert.match(output.answer,/12%/);
const rows=run('data src=table([{t:DateTimeTz("2026-01-01T01:00:00.000+01:00[Europe/Paris]")},{t:DateTimeTz("2025-12-31T20:00:00.000-05:00[America/New_York]")}]);data rows=query! {let a=from(src);let result=project({t:a.t,utc:to_datetime_utc(a.t),day:time_bucket(a.t,{unit:TimeUnit::Day,time_zone:"UTC"})});result |> order_by(asc(result.t)) |> take(2)};').rows;
assert.deepEqual(rows.map((r:any)=>r.utc),['2026-01-01T00:00:00.000Z','2026-01-01T01:00:00.000Z']);
assert.equal(rows[0].day,'2026-01-01T00:00:00.000Z');
console.log('Shared types: independent ratios, strict time codecs, instant arithmetic/order, explicit zones and DST buckets passed');
