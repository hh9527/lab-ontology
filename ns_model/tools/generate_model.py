#!/usr/bin/env python3
"""Generate explicit typed declarations from the checked-in migration contract."""
import json
import hashlib
import re
from unit_names import unit_type_name
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
M=json.loads((ROOT/'data/source-model.json').read_text())
Q=lambda s:json.dumps(s,ensure_ascii=False)
A=lambda xs:'['+', '.join(xs)+']'
S=lambda v:v['symbol'].split('::')[-1]
D={d['id']:d for d in M['datasets']}
N={d['id']:re.sub(r'[^a-zA-Z0-9_]','_',d['id']) for d in M['datasets']}
F={(d['id'],f['name']):f for d in M['datasets'] for f in d['fields']}
PRE='''# Generated by tools/generate_model.py; source evidence is in data/source-model.json.
use ontology::model as m;
use ontology::groups as g;
use ontology::scalars as s;
use ontology::samples as sample;
use ontology::values as v;
use ontology::transform as t;
use ontology::world as w;
use ontology::relations as r;
use ontology::ontology as edsl;
use ontology::query as qb;
'''
issues=[]
def fieldtype(d,f):
    if f['time_field']:
        sem,enc=map(S,f['time_field'][0])
        if enc=='Rfc3339Text':return 's::DateTimeUtc'
        if enc=='LocalText':return 's::DateTime'
        if enc=='DateText':return 's::Date'
        # Only a source-confirmed millisecond unit warrants an EpochMillis type.
        evidence=' '.join(str(f['source'].get(k) or '') for k in ['description','description_cn','businessName','businessName_cn'])
        if enc=='EpochMillis' and ('毫秒' in evidence or 'millisecond' in evidence.lower()):return 's::EpochMillis'
        issues.append({'kind':'unconfirmed_time_unit','dataset':d['id'],'field':f['name'],'legacy':f['time_field']})
    return f['storage']
TY={(d['id'],f['name']):fieldtype(d,f) for d in D.values() for f in d['fields']}
# Nominal units reuse the source's explicit/assumed unit contract without
# inventing arithmetic conversions or additive semantics.
unit_types={}
for d in D.values():
    for f in d['fields']:
        unit=None
        if f['measure_family']:unit=f['measure_family'][0][0]['source']['unit']
        elif f['sample_measure']:
            u=f['sample_measure'][0][2]
            if u!={'symbol':'None'}:unit=u['args'][0]
        if unit is not None:
            key=(unit,f['storage'])
            unit_types.setdefault(key,unit_type_name(*key))
            TY[d['id'],f['name']]='units::'+unit_types[key]
(ROOT/'src/units.telora').write_text('# Nominal source units; see source-model.json for evidence and assumptions.\n'+'\n'.join(f'pub type {name} = struct({storage}); # {unit}' for (unit,storage),name in unit_types.items())+'\n')
PRE+='use crate::units as units;\n'
def nullable(d,f):return f['source'].get('nullable')!='N' and f['name'] not in d['grain']
def witness(d,f):return f'm::{"optional_field" if nullable(d,f) else "field"}(Row.type, {TY[d["id"],f["name"]]}.type, {Q(f["name"])})'
def inputof(d,f):return f'g::input({witness(d,f)})'
# Explicit equivalence classes of identity tuples, based only on declared equality.
parent={}
def find(x):
    parent.setdefault(x,x)
    if parent[x]!=x:parent[x]=find(parent[x])
    return parent[x]
def union(a,b):parent[find(b)]=find(a)
def pairs(key):
    if key['call'].endswith('::FieldEq'):return [key['args'][0]]
    assert key['call'].endswith('::And'),key
    return [p for k in key['args'][0] for p in pairs(k)]
for d in D.values():
    if d['kind']=='Entity' and not d['internal']:find((d['id'],tuple(d['grain'])))
for rel in M['relations']:
    ps=pairs(rel['key']);union((rel['from'],tuple(p['from'] for p in ps)),(rel['to'],tuple(p['to'] for p in ps)))
components={}
for x in parent:components.setdefault(find(x),[]).append(x)
ids={}; identity_lines=[]; entity_names=[]; type_names=[]
for i,entries in enumerate(components.values()):
    owner=next((x for x in entries if D[x[0]]['kind']=='Entity' and not D[x[0]]['internal'] and list(x[1])==D[x[0]]['grain']),None)
    namespace=owner[0] if owner else 'reference/'+entries[0][0]+'/'+','.join(entries[0][1])
    count=len(entries[0][1]); ident=f'Identity{i}'; en=f'entity_{i}'
    members=[]
    for j in range(count):
        storage={F[d,k[j]]['storage'] for d,k in entries};assert len(storage)==1,entries
        raw=next(iter(storage));assert raw in ['String','Int'],entries
        ty=f'Key{i}_{j}';identity_lines.append(f'pub type {ty} = struct({raw});');members.append(f'k{j}: {ty}');type_names.append(f'ids::{ty}.type')
    identity_lines.append(f'pub type {ident} = struct {{ '+', '.join(members)+' };')
    identity_lines.append(f'pub def {en}: m::Entity({ident}) = m::entity({Q(namespace)}, {ident}.type);')
    type_names.append(f'ids::{ident}.type');entity_names.append(f'w::entity(ids::{en})')
    for entry in entries:ids[entry]=(i,ident,en)
(ROOT/'src/identities.telora').write_text(PRE+'\n'.join(identity_lines)+'\n')
# Shared groups are reused by type, projection policy, filters and statistic set.
groups={};group_lines=[]
def group(key,expr,ty):
    if key not in groups:
        name='group_'+str(len(groups));groups[key]=name;group_lines.append(f'pub def {name}: {ty} = {expr};')
    return 'groups::'+groups[key]
# Canonical domains keep the original public business IDs and physical wires.
domain_lines=['use ontology::knowledge_policy as knowledge_policy;']
for name,v in M['domains'].items():
    ty='Domain_'+name;wire=v['wire'];members=[]
    for member in v['values']:
        members.append(f'v::member({ty}({Q(member["id"])}), '+A(Q(w['args'][0]) for w in member['wires'])+')')
    domain_lines.extend([f'@knowledge_policy::reverse_references(True)\npub type {ty} = struct(String);',f'pub def {name}: v::Domain({ty}, {wire}) = v::domain({Q(v["name"])}, {ty}.type, {wire}.type, {A(members)}, {str(v["halfOpen"]) });'])
    type_names.append(f'domains::{ty}.type')
(ROOT/'src/domains.telora').write_text(PRE+'\n'.join(domain_lines)+'\n')
roles={};decls=[];published_specs={}
for d in D.values():
    name=N[d['id']];lines=[PRE,'use crate::identities as ids;','use crate::groups as groups;','use crate::domains as domains;']
    fields=[]
    for f in d['fields']:
        ty=TY[d['id'],f['name']];fields.append(f'{f["name"]}: '+(f'Option({ty})' if nullable(d,f) else ty))
        if not nullable(d,f) and f['source'].get('nullable')!='N':issues.append({'kind':'required_grain_assumption','dataset':d['id'],'field':f['name']})
    lines.append('pub type Row = struct { '+', '.join(fields)+' };')
    lines.append(f'pub def dataset: m::Dataset(Row) = m::dataset({Q(d["id"])}, {Q(d["table"])}, Row.type, {Q(d["grain"])});')
    role_names=[]
    for role_index,(entry,(i,ident,en)) in enumerate(ids.items()):
        if entry[0]!=d['id']:continue
        rn=f'role_{role_index}';parts=[]
        for j,fn in enumerate(entry[1]):
            f=F[d['id'],fn];assert TY[d['id'],fn] in ['Int','String'],entry
            parts.append(f'm::reference_part({witness(d,f)}, m::field(ids::{ident}.type, ids::Key{i}_{j}.type, "k{j}"))')
        opt=any(nullable(d,F[d['id'],fn]) for fn in entry[1]);lines.append(f'pub def {rn}: m::Role(Row) = m::role(dataset, ids::{en}, {Q(rn)}, {opt}, {A(parts)});');role_names.append(rn);roles[entry]=rn
    bindings=[];domain_bindings=[];samples=[];counts=[]
    for f in d['fields']:
        ty=TY[d['id'],f['name']];witness_expr=witness(d,f);inp=inputof(d,f)
        for dim in f['dimension']:
            public,projectable,filterable,ops,_=dim;ops=[S(op) for op in ops] if filterable else []
            if f['dimension_type']:
                dn=S(f['dimension_type'][0][0]).removesuffix('.type');domain_bindings.append(f'v::bind(dataset, v::dimension_group(domains::{dn}, {projectable}, '+A('g::Filter::'+o for o in ops)+f'), {inp}, {Q(public)}, {projectable}, '+A('g::Filter::'+o for o in ops)+')')
            else:
                if ty in ['Int','String'] and f['time_field']:ops=[o for o in ops if o in (['Eq','Ne'] if ty=='String' else ['Eq','Ne','Gt','Ge','Lt','Le'])]
                filters=A('g::Filter::'+o for o in ops);key=('dimension',ty,projectable,tuple(ops));gr=group(key,f'g::dimension_group("ns/dimension/{len(groups)}", {ty}.type, {projectable}, {filters})',f'g::DimensionGroup({ty})')
                bindings.append(f'g::dimension(dataset, {gr}, {inp}, {Q(public)}, {projectable}, {filters})')
        for public,unit in f['utc_bucket_dimension']:
            if ty not in ['s::EpochMillis','s::DateTimeUtc','s::Date']:issues.append({'kind':'untyped_bucket','dataset':d['id'],'field':f['name'],'public':public});continue
            filters='g::time_filters';outty=ty
            gr=group(('bucket',outty),f'g::dimension_group("ns/bucket/{outty.split("::")[-1]}", {outty}.type, True, g::time_filters)',f'g::DimensionGroup({outty})')
            bindings.append(f'g::dimension(dataset, {gr}, g::utc_bucket({inp}, qb::UtcBucketUnit::{S(unit)}), {Q(public)}, True, {filters})')
        for public,agg,_ in f['measure']:
            assert S(agg)=='Count';counts.append(f't::field_count(dataset, {witness_expr}, {Q(public)})')
        specs=[];unit=None
        if f['measure_family']:
            fam=f['measure_family'][0][0];naming={S(x['role']):x['suffix'] for x in fam['naming']['args'][0]};unit=fam['source']['unit'];specs=[(S(v),fam['id']+naming[S(v)]) for v in fam['variants']]
        elif f['sample_measure']:
            public,agg,u=f['sample_measure'][0];unit=None if u=={'symbol':'None'} else u['args'][0];specs=[(S(agg),public)]+[(S(a),p) for p,a,_ in f['sample_aggregate']]
        if any(stat=='Sum' for stat,_ in specs):
            issues.append({'kind':'unconfirmed_additive_sample','dataset':d['id'],'field':f['name'],'omitted':[public for stat,public in specs if stat=='Sum']})
            specs=[(stat,public) for stat,public in specs if stat!='Sum']
        published_specs[d['id'],f['name']]=[{'id':p,'statistic':'Mean' if stat=='Avg' else stat} for stat,p in specs]
        if specs:
            stat=lambda x:'Mean' if x=='Avg' else x
            key=('samples',ty,unit,tuple(x[0] for x in specs));primary=stat(specs[0][0]);rest=A('sample::Statistic::'+stat(x[0]) for x in specs[1:]);un='None' if unit is None else f'Some({Q(unit)})'
            gr=group(key,f'sample::group("ns/sample/{len(groups)}", {ty}.type, sample::Statistic::{primary}, {rest}, {un})',f'sample::Group({ty})')
            samples.append(f'sample::bind(dataset, {gr}, {witness_expr}, '+A('{statistic: sample::Statistic::'+stat(s)+', publish: '+Q(p)+'}' for s,p in specs)+')')
    expr=f't::declare(dataset, {A(role_names)}, {A(bindings)}, [])'
    expr=f't::map_columns({expr}, '+A(f't::column({witness(d,f)}, {Q(f["column"])})' for f in d['fields'])+')'
    if counts:expr=f't::with_field_counts({expr}, {A(counts)})'
    if domain_bindings:expr=f't::with_domains({expr}, {A(domain_bindings)})'
    if samples:expr=f't::with_samples({expr}, {A(samples)})'
    if d['clock']:
        f=F[d['id'],d['clock']]
        if TY[d['id'],f['name']] not in ['s::EpochMillis','s::DateTimeUtc']:issues.append({'kind':'unconfirmed_clock','dataset':d['id'],'field':f['name']})
        else:expr=f't::{"metric" if d["kind"]=="Metric" else "event"}({expr}, {witness(d,f)})'
    lines.append(f'pub def declaration: t::Declaration = {expr};')
    (ROOT/f'src/datasets/{name}.telora').write_text('\n'.join(lines)+'\n');type_names.append(f'{name}::Row.type');decls.append(f'{name}::declaration')
(ROOT/'src/groups.telora').write_text(PRE+'\n'.join(group_lines)+'\n')
rels=[]
for rel in M['relations']:
    ps=pairs(rel['key']);a,b=rel['from'],rel['to'];ak=(a,tuple(p['from'] for p in ps));bk=(b,tuple(p['to'] for p in ps));card='{from: edsl::Cardinality::'+rel['cardinality']['from']+', to: edsl::Cardinality::'+rel['cardinality']['to']+'}'
    expr=f'r::relation({Q(rel["id"])}, {N[a]}::dataset, {N[a]}::{roles[ak]}, {N[b]}::dataset, {N[b]}::{roles[bk]}, {card})'
    if rel['guard']:
        gu=rel['guard'];f=F[a,gu['field']];wi=witness(D[a],f).replace('Row.type',N[a]+'::Row.type');expr=f'r::guarded({expr}, {wi}, edsl::FilterOp::{S(gu["op"])}, {Q(gu["input"]["args"][0])})'
    rels.append(expr)
mods=''+'\n'.join(f'use crate::datasets::{N[d]} as {N[d]};' for d in D)
(ROOT/'src/datasets.telora').write_text('\n'.join(f'pub mod {N[d]};' for d in D)+'\n')
type_names += ['units::'+name+'.type' for name in unit_types.values()]
scalar_types=sorted({ty for ty in TY.values() if ty.startswith('s::')}|{'s::Date','s::DateTimeUtc'})
world=PRE+'\nuse crate::identities as ids;\nuse crate::domains as domains;\nuse crate::profile as profile;\n'+mods+'\n'
world+=f'pub def model_world: w::World = w::define("ns/typed-v1", {A(decls)}, {A(rels)}, [], [], profile::profile);\n'
(ROOT/'src/model.telora').write_text(world)
(ROOT/'data/migration-decisions.json').write_text(json.dumps({'issues':issues,'pathDeclarations':M['paths'],'sourceRelations':M['catalog']['relations']},ensure_ascii=False,indent=2)+'\n')
# A compact fixture contract uses the same resolved types and nullability as
# the emitted model. Data generation does not reinterpret legacy time annotations.
contract_datasets=[]
for d in D.values():
    fields=[]
    for f in d['fields']:
        domain=S(f['dimension_type'][0][0]).removesuffix('.type') if f['dimension_type'] else None
        fields.append({
            'name':f['name'], 'column':f['column'], 'storage':f['storage'],
            'type':TY[d['id'],f['name']], 'nullable':nullable(d,f), 'domain':domain,
            'dimensions':[{'id':dim[0],'projectable':dim[1],'filterable':dim[2]} for dim in f['dimension']],
            'metric':bool(f['measure_family'] or f['sample_measure'] or f['sample_aggregate']),
            'unit':next((u for (u,_),n in unit_types.items() if TY[d['id'],f['name']]=='units::'+n),None),
            'sourceTimeEncoding':S(f['time_field'][0][1]) if f['time_field'] else None,
            'measures':published_specs[d['id'],f['name']],
        })
    contract_datasets.append({k:d[k] for k in ['id','table','kind','internal','grain','clock']} | {'fields':fields})
contract={
    'version':1, 'sourceCommit':M['sourceCommit'],
    'sourceSha256':hashlib.sha256((ROOT/'data/source-model.json').read_bytes()).hexdigest(),
    'generatedHashes':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT/'src').rglob('*.telora'))},
    'datasets':contract_datasets,
    'relations':[{k:r[k] for k in ['id','from','to','cardinality','guard']} | {'pairs':pairs(r['key'])} for r in M['relations']],
    'domains':{name:{'name':v['name'],'wire':v['wire'],'halfOpen':v['halfOpen'],
        'members':[{'id':x['id'],'label':x['label'],'wires':[w['args'][0] for w in x['wires']]} for x in v['values']]} for name,v in M['domains'].items()},
}
(ROOT/'data/generation-contract.json').write_text(json.dumps(contract,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'datasets':len(D),'fields':len(F),'identities':len(components),'relations':len(rels),'groups':len(groups),'decisions':len(issues)}))
