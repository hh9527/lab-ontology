#!/usr/bin/env python3
"""将静态 JS 程序嵌入 Telora 源码；--check 校验生成文件未漂移。"""
import argparse
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
source=root/'ontology/src/experimental/knowledge.js';target=source.with_name('knowledge_program.telora')
content='# Generated by scripts/embed-knowledge-program.py; edit knowledge.js.\n'
content+='def program: String = '+json.dumps(source.read_text(),ensure_ascii=False)+';\npub use self::{program};\n'
if args.check:
 assert target.read_text()==content,'Run scripts/embed-knowledge-program.py'
else:target.write_text(content)
