import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {check} from './src/compiler.ts';
import {resolve} from './src/runtime.ts';
const {dariHost}=await import(new URL('../../dsh-oks/packages/dsh-oks/src/dari-host.ts',import.meta.url).href);
const db=new DatabaseSync(':memory:');
const render=(body:string)=>resolve(check(body,undefined,{host:dariHost}),db);
const text=(svg:string)=>(svg.match(/<text\b[^>]*>[\s\S]*?<\/text>/g)??[]).join('');
const source=`data p=Ratio(0.1234567);data f=1.005;data n=123456;data rows=table([{name:"A",p:p}]);answer tree! {Answer [Value(value = p),Value(value = f),Value(value = n),Value(value = p,precision = 3),Table(data = rows),BarChart(data = rows,spec = {x:project!(name),value:project!(p),style:{labels:True}})]};`;
const result=render(source);
assert.match(result.answer,/12.35%/);assert.match(result.answer,/1.01/);assert.match(result.answer,/123456/);assert.match(result.answer,/12.346%/);
const svg=result.artifacts['chart_1.svg'];
assert.match(text(svg),/12.35%/);assert(!text(svg).includes('12.34567'));
assert.match(svg,/A,0.1234567/);assert.equal(result.values.p,0.1234567);
const stacked=`data rows=table([{x:"A",s:"One",n:1},{x:"A",s:"Two",n:2}]);answer tree! {Answer [GroupedBarChart(data = rows,spec = {x:project!(x),series:project!(s),value:project!(n),stack:Stack::Percent,style:{labels:True}})]};`;
assert.match(text(render(stacked).artifacts['chart_1.svg']),/33.33%/);
assert.match(text(render(stacked.replace('Stack::Percent','Stack::Total')).artifacts['chart_1.svg']),/>1</);
render(stacked.replace('Stack::Percent','Stack::None'));
assert.throws(()=>render(stacked.replace('Stack::Percent','{enum:"Stack",variant:"Total"}')),/stack requires Stack::/);
assert.throws(()=>render(stacked.replace('Stack::Percent','True')),/stack requires Stack::/);
assert.throws(()=>render(stacked.replace('Stack::Percent','"total"')),/stack requires Stack::/);
assert.throws(()=>render(stacked.replace('Stack::Percent','Stack::Bogus')),/Unknown enum variant/);
const rates=`data rows=table([{x:"A",s:"One",n:Ratio(0.1)},{x:"A",s:"Two",n:Ratio(0.2)}]);answer tree! {Answer [GroupedColumnChart(data = rows,spec = {x:project!(x),series:project!(s),value:project!(n),stack:Stack::Total})]};`;
assert.throws(()=>render(rates),/does not allow Sum/);
render(rates.replace('Stack::Total','Stack::None'));
const wide=`data rows=table([{x:"A",a:Ratio(0.1234567),b:Percent(56.789123)}]);answer tree! {Answer [GroupedColumnChart(data = rows,spec = {x:project!(x),series:[{value:project!(a),label:"A",unit:"%"},{value:project!(b),label:"B",unit:"%"}],stack:Stack::None,style:{labels:True}})]};`;
assert.match(text(render(wide).artifacts['chart_1.svg']),/12.35%/);
assert.throws(()=>render(source.replace('precision = 3','precision = 13')),/0..12/);
assert.throws(()=>render(source.replace('style:{labels:True}','precision:-1,style:{labels:True}')),/0..12/);
const fine={kind:'nominal',name:'Fine',inner:{kind:'scalar',name:'Float'},presentation:{multiplier:1,suffix:'',precision:4}};
const host={...dariHost,types:{...dariHost.types,Fine:fine}};
const fineSource='data v=Fine(1.234567);data digits=3;answer tree! {Answer [Value(value = v),Value(value = v,precision = digits)]};';
assert.equal(resolve(check(fineSource,undefined,{host}),db).answer,'*1.2346*\n\n*1.235*');
db.close();
console.log('Chart types: Stack enum, additive constraints, grouped bars, ratio scale, shared precision/overrides, raw CSV and model defaults passed');
