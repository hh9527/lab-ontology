// End-to-end: Telora properties -> World publication -> graph -> summary/card.
import assert from 'node:assert/strict';
import {cpSync,readFileSync,writeFileSync,mkdirSync,mkdtempSync} from 'node:fs';
import {homedir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {derivePublishedKnowledge} from '../../dsh-oks/packages/dsh-oks/src/published-knowledge.ts';
import {domainSummary} from '../../dsh-oks/packages/dsh-oks/src/domain-summary.ts';
import {semanticKnowledge} from '../../dsh-oks/packages/dsh-oks/src/semantic-knowledge.ts';
const root=fileURLToPath(new URL('../',import.meta.url));
const base=process.env.TMPDIR || join(homedir(),'.cache/tmp');mkdirSync(base,{recursive:true});
const work=mkdtempSync(join(base,'field-business-roles-'));
cpSync(join(root,'ontology'),join(work,'ontology'),{recursive:true});
mkdirSync(join(work,'roles/src'),{recursive:true});
writeFileSync(join(work,'roles/telora-crate.json'),JSON.stringify({name:'roles',dependencies:['ontology']}));
writeFileSync(join(work,'telora-config.json'),JSON.stringify({version:1,members:['ontology','roles']}));
writeFileSync(join(work,'roles/src/lib.telora'),readFileSync(join(root,'ontology/tests/typed_field_roles.telora'),'utf8').replaceAll('use crate::','use ontology::'));
const lock=spawnSync(join(root,'bin/telora'),['-C',join(work,'roles'),'lock'],{encoding:'utf8'});
assert.equal(lock.status,0,lock.stderr);
const run=spawnSync(join(root,'bin/telora'),['-C',join(work,'roles'),'eval','roles:publication'],{encoding:'utf8',maxBuffer:16*1024*1024});
assert.equal(run.status,0,run.stderr);
const publication=JSON.parse(run.stdout);
writeFileSync(join(work,"publication.json"),run.stdout);
const built=new Function('data',publication.program)(publication.data);
const {knowledge:graph}=derivePublishedKnowledge(built.graph,undefined,built.vocabulary);
const d=graph.datasets.objects;
assert.deepEqual(d.references,[{id:'scoped',fields:['tenant','local']}]);
assert.deepEqual(d.fields.name.roles,['Appellation']);
assert.deepEqual(d.fields.category.roles,['Appellation','Classification']);
assert.deepEqual(d.fields.amount.roles,['Metric']);
assert.deepEqual(d.fields.unclassified_number.roles,[]);
assert.deepEqual(d.fields.tenant.roles,['Reference']);
assert.equal(d.roles.subject.parts.length,2);
const summary=domainSummary(graph,'roles');
assert.deepEqual(summary.datasets[0].references,d.references);
assert.equal(summary.datasets[0].field_roles.length,5);
const read=args=>semanticKnowledge(graph,'card',{...args,id:'datasets/objects'});
const card=read({section:'fields',skip:0,take:2});
assert.deepEqual(card.references,d.references,'pagination must retain complete reference groups');
assert.equal(card.fields.length,2);
assert.equal(card.counts.fields,6);
assert.equal(card.field_roles.length,5);
const shape=read({section:'shape'});
assert.deepEqual(shape.field_roles,card.field_roles);
const roles=read({section:'roles'});
assert.equal(roles.roles[0].facts.parts.length,2);
assert.equal(roles.roles[0].facts.entity,'entities/object');
console.log(JSON.stringify({worldPublication:true,overlappingRoles:true,scopedCompositeReference:true,noNumericGuessing:true,summary:true,card:true,work}));
