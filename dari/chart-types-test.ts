import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {check} from './src/compiler.ts';
import {resolve} from './src/runtime.ts';
const {dariHost}=await import(new URL('../../dsh-oks/packages/dsh-oks/src/dari-host.ts',import.meta.url).href);
const db=new DatabaseSync(':memory:');
const render=(body:string)=>resolve(check(body,undefined,{host:dariHost}),db);
const text=(svg:string)=>(svg.match(/<text\b[^>]*>[\s\S]*?<\/text>/g)??[]).join('');
const source=`data p=Ratio(0.1234567);data f=1.005;data n=123456;data rows=table([{name:"A",p:p}]);answer tree! {Answer [Value(value = p),Value(value = f),Value(value = n),Value(value = p,precision = 3),Table(data = rows),BarChart(data = rows,spec = {category:project!(name),value:project!(p),style:{labels:True}})]};`;
const result=render(source);
assert.match(result.answer,/12.35%/);assert.match(result.answer,/1.01/);assert.match(result.answer,/123456/);assert.match(result.answer,/12.346%/);
const svg=result.artifacts['chart_1.svg'];
assert.match(text(svg),/12.35%/);assert(!text(svg).includes('12.34567'));
assert.match(svg,/A,0.1234567/);assert.equal(result.values.p,0.1234567);
const stacked=`data rows=table([{x:"A",s:"One",n:1},{x:"A",s:"Two",n:2}]);answer tree! {Answer [StackedBarChart(data = rows,spec = {category:project!(x),series:project!(s),value:project!(n),mode:StackMode::Percent,style:{labels:True}})]};`;
assert.match(text(render(stacked).artifacts['chart_1.svg']),/33.33%/);
assert.match(text(render(stacked.replace('StackMode::Percent','StackMode::Absolute')).artifacts['chart_1.svg']),/>1</);
render(stacked.replace(',mode:StackMode::Percent',''));
assert.throws(()=>render(stacked.replace('StackMode::Percent','{enum:"Stack",variant:"Total"}')),/Use StackMode::/);
assert.throws(()=>render(stacked.replace('StackMode::Percent','True')),/Use StackMode::/);
assert.throws(()=>render(stacked.replace('StackMode::Percent','"total"')),/Use StackMode::/);
assert.throws(()=>render(stacked.replace('StackMode::Percent','StackMode::Bogus')),/Unknown enum variant/);
const rates=`data rows=table([{x:"A",s:"One",n:Ratio(0.1)},{x:"A",s:"Two",n:Ratio(0.2)}]);answer tree! {Answer [StackedBarChart(data = rows,spec = {category:project!(x),series:project!(s),value:project!(n),mode:StackMode::Absolute})]};`;
assert.throws(()=>render(rates),/does not allow Sum/);
render(rates.replace('StackedBarChart','GroupedBarChart').replace(',mode:StackMode::Absolute',''));
const wide=`data rows=table([{x:"A",a:Ratio(0.1234567),b:Percent(56.789123)}]);answer tree! {Answer [MultiBarChart(data = rows,spec = {category:project!(x),metrics:[{value:project!(a),label:"A",unit:"%"},{value:project!(b),label:"B",unit:"%"}],style:{labels:True}})]};`;
assert.match(text(render(wide).artifacts['chart_1.svg']),/12.35%/);
for(const code of [source,stacked,wide,rates.replace('StackedBarChart','GroupedBarChart').replace(',mode:StackMode::Absolute','')]){
 const vertical=render(code).artifacts['chart_1.svg'];
 const horizontal=render(code.replace('spec = {','spec = {orientation:Orientation::Horizontal,')).artifacts['chart_1.svg'];
 assert.notEqual(horizontal,vertical);
 assert.match(horizontal,/<svg/);
 assert.throws(()=>render(code.replace('spec = {','spec = {orientation:"Horizontal",')),/Use Orientation::/);
}
assert.throws(()=>render(wide.replace('MultiBarChart','GroupedBarChart')),/independent columns use MultiBarChart/);
assert.throws(()=>render(stacked.replace('StackedBarChart','GroupedBarChart')),/Only StackedBarChart accepts mode/);
assert.throws(()=>render(source.replace('BarChart','ColumnChart')),/Unknown component ColumnChart/);
assert.throws(()=>render(source.replace('category:project!','x:project!')),/uses category/);
assert.throws(()=>render(source.replace('precision = 3','precision = 13')),/0..12/);
assert.throws(()=>render(source.replace('style:{labels:True}','precision:-1,style:{labels:True}')),/0..12/);
const fine={kind:'nominal',name:'Fine',inner:{kind:'scalar',name:'Float'},presentation:{multiplier:1,suffix:'',precision:4}};
const host={...dariHost,types:{...dariHost.types,Fine:fine}};
const fineSource='data v=Fine(1.234567);data digits=3;answer tree! {Answer [Value(value = v),Value(value = v,precision = digits)]};';
assert.equal(resolve(check(fineSource,undefined,{host}),db).answer,'*1.2346*\n\n*1.235*');
db.close();
console.log('Chart contracts: four components, two orientations, stack modes, additive constraints, ratio scale, precision and raw CSV passed');
